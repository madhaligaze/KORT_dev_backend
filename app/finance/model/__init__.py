"""API модели - семь вызовов ядра вместо маршрутов под экраны (этап 2, шаг 7).

Ядро как операционная система: оболочки (веб, десктоп, бот, выгрузка, холст,
чужой сервис) приходят и уходят, а вызовы остаются. До 28.10.2026 у KORT было
270 маршрутов, нарезанных под экраны (`/today/debts`, `/start/{step}`,
`/switch/{link}`), и новый фронт пришлось бы писать под них. Здесь - семь
вызовов, из которых новый экран складывается без новой работы на сервере:

1. **Описать** (`describe.py`) - схема компании: поля со смыслами, меры,
   источники и виды, наши юрлица, отделы, команды и что из этого можно тому,
   кто спрашивает. Фронт рисует по ней, а не по зашитому коду.
2. **Спросить** (`ask.py`) - любой вид на любой день: сохранённый или вопрос
   без сохранения (источник, отбор, меры, группировки). Источники - договоры
   листами, долги, счета к выставлению. У каждого числа, которое
   раскрывается, - `ref`.
3. **Объяснить** (`explain.py`) - число по `ref` до слагаемых, слагаемые - до
   фактов журнала: итог части листа → договоры → оплаты; долг группы →
   договоры → сальдо, начисления, оплаты.
4. **Предложить** (`apply.propose`) - команды прогоном в транзакции, которая
   откатывается: что заведётся, что изменится, долг до и после - до записи.
5. **Применить** (`apply.apply`) - пачка команд одной транзакцией и одной
   точкой восстановления.
6. **Отменить** (`apply.undo`) - по точке восстановления.
7. **Подписаться** (`stream.py`) - что изменилось после курсора: договоры,
   факты журнала, операции, схема - одним курсором.

Пакет не знает про HTTP (маршруты - `app/api/routes/finance_model.py`) и не
считает сам: он спрашивает ядро (`core/views.py`, `core/debts.py`,
`core/calls.py`, `contracts/service.py`, `contracts/restore.py`) и отдаёт его
числа одной формой.

Версия
──────
`VERSION` - «старшая.младшая». Добавить поле, команду или источник - младшая
цифра: старый клиент нового поля не заметит. Сменить смысл поля или убрать
его - старшая: клиент, приславший `X-Kort-Model` с другой старшей цифрой,
получает отказ словами, а не чужие поля молча.
"""
